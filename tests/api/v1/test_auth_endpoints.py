@pytest.mark.asyncio
async def test_password_recovery_request(client: AsyncClient, db_session):
    email = unique_email()
    password = "RecoveryPassword789"

    # 1. Register a user
    await client.post("/api/v1/auth/register", json={"email": email, "password": password})

    # 2. Request password recovery for an existing user
    response = await client.post(f"/api/v1/auth/password-recovery/{email}")
    assert response.status_code == status.HTTP_200_OK
    assert "Password recovery email sent" in response.json()["msg"] # Or similar message

    # 3. Request password recovery for a non-existent user
    non_existent_email = unique_email()
    response_non_existent = await client.post(f"/api/v1/auth/password-recovery/{non_existent_email}")
    assert response_non_existent.status_code == status.HTTP_404_NOT_FOUND


