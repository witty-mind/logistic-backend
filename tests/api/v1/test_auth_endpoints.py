# Helper to generate unique email
def unique_email() -> str:
    return f"testuser_{uuid.uuid4().hex[:6]}@example.com"

@pytest.mark.asyncio
async def test_user_registration(client: AsyncClient, db_session): # Add db_session for potential cleanup or setup if needed
    email = unique_email()
    password = "SecurePassword123"
    
    # 1. Register a new user
    response = await client.post(
        "/api/v1/auth/register",
        json={"email": email, "password": password},
    )
    assert response.status_code == status.HTTP_200_OK # Based on current endpoint returning 200
    user_data = response.json()
    assert user_data["email"] == email
    assert "id" in user_data
    assert "hashed_password" not in user_data # Ensure password is not returned

    # 2. Attempt to register the same user again
    response_conflict = await client.post(
        "/api/v1/auth/register",
        json={"email": email, "password": password},
    )
    assert response_conflict.status_code == status.HTTP_400_BAD_REQUEST
    assert "Email already registered" in response_conflict.json()["detail"]

@pytest.mark.asyncio
async def test_user_login(client: AsyncClient, db_session):
    email = unique_email()
    password = "LoginPassword456"

    # 1. Register a user first (ensure user exists for login test)
    await client.post("/api/v1/auth/register", json={"email": email, "password": password})

    # 2. Log in with correct credentials
    login_response = await client.post(
        "/api/v1/auth/login",
        data={"username": email, "password": password}, # OAuth2PasswordRequestForm uses form data
    )
    assert login_response.status_code == status.HTTP_200_OK
    token_data = login_response.json()
    assert "access_token" in token_data
    assert "refresh_token" in token_data
    assert token_data["token_type"] == "bearer"

    # 3. Attempt to log in with incorrect password
    login_fail_password_response = await client.post(
        "/api/v1/auth/login",
        data={"username": email, "password": "WrongPassword"},
    )
    assert login_fail_password_response.status_code == status.HTTP_401_UNAUTHORIZED
    assert "Incorrect email or password" in login_fail_password_response.json()["detail"]

    # 4. Attempt to log in with a non-existent user
    non_existent_email = unique_email()
    login_fail_user_response = await client.post(
        "/api/v1/auth/login",
        data={"username": non_existent_email, "password": password},
    )
    assert login_fail_user_response.status_code == status.HTTP_401_UNAUTHORIZED # Or 404 depending on strict error handling
    assert "Incorrect email or password" in login_fail_user_response.json()["detail"]


